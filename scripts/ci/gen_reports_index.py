"""Generate, or check, the index of ``TECHNICAL_REPORTS/``.

Rationale
---------
``TECHNICAL_REPORTS/`` holds one English and one Korean report per merged PR,
hundreds of them, and before issue #1708 it had no index and no inbound link,
so nobody could find a report or map a PR number to one. A hand-kept index
would drift on the next report, so the index is generated from the files and
CI fails when the committed copy differs from what this script would write.

What the index holds
--------------------
One row per report, keyed by its stem (the file name without ``.en.md`` or
``.ko.md``), newest number first:

- the number: the leading digits of the stem (``1058-...`` or ``pr-2475-...``),
  which is the PR the report covers in all but a handful of cases;
- the title: the report's first ``# `` heading, with the boilerplate
  ``Technical Report:`` and ``PR #N -`` prefixes removed (English file first);
- the date: the ``YYYYMMDD`` suffix of the stem, else a ``Date`` or ``Updated``
  line in the report's header, else blank;
- links to the English and Korean files. A missing language shows as ``-``.

Usage
-----
    scripts/ci/gen_reports_index.py          # rewrite TECHNICAL_REPORTS/README.md
    scripts/ci/gen_reports_index.py --check  # exit 1 if it is stale

Regenerate after adding or renaming a report (``make reports-index``).
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
REPORTS_DIR = ROOT / "TECHNICAL_REPORTS"
INDEX_NAME = "README.md"
LANGS = ("en", "ko")
REPO_URL = "https://github.com/lablup/mlxcel"

_REPORT_RE = re.compile(r"^(?P<stem>.+)\.(?P<lang>en|ko)\.md$")
_NUMBER_RE = re.compile(r"^(?:pr-)?(?P<num>\d+)-")
_STEM_DATE_RE = re.compile(r"-(?P<y>20\d\d)(?P<m>[01]\d)(?P<d>[0-3]\d)$")
_HEADER_DATE_RE = re.compile(
    r"^\*\*(?:Date|Updated)(?::\*\*|\*\*:)\s*(?P<date>\d{4}-\d{2}-\d{2})"
)
_TITLE_PREFIX_RE = re.compile(r"^Technical [Rr]eport\s*:\s*")
_TITLE_REF_RE = re.compile(
    r"^(?:(?:PR|Issue)\s+#\d+|PR\s+\(issue\s+#\d+\))\s*(?:[-:,–—]\s*)?"
)
_TITLE_SUFFIX_RE = re.compile(
    r"\s*(?:\((?:PR |issue )?#\d+\)|[-:–—]\s*PR\s+#\d+)$"
)
HEADER_LINES = 20

PREAMBLE = """\
# Technical reports

This directory holds one technical report per merged change, each in English
(`.en.md`) and Korean (`.ko.md`). A report records what the change did, how it
was validated and what it left open. The number is the one in the file name,
which is the PR the report covers in nearly every case.

This index is generated by `scripts/ci/gen_reports_index.py` from the file
names and each report's title and date lines. Do not edit it by hand: after
adding or renaming a report, run `make reports-index`. CI fails when this file
is stale.
"""


class Report:
    def __init__(self, stem: str) -> None:
        self.stem = stem
        self.files: dict[str, str] = {}
        self.title = ""
        self.date = ""

    @property
    def number(self) -> int | None:
        match = _NUMBER_RE.match(self.stem)
        return int(match.group("num")) if match else None


def clean_title(heading: str) -> str:
    title = heading.strip()
    title = _TITLE_PREFIX_RE.sub("", title)
    title = _TITLE_REF_RE.sub("", title)
    title = _TITLE_SUFFIX_RE.sub("", title)
    # Keep the table a table: a raw pipe would split the cell.
    title = title.replace("|", "\\|")
    return title.replace("—", "-").strip()


def read_header(path: pathlib.Path) -> tuple[str, str]:
    """Return (first H1 heading, header date) from the top of a report."""
    heading = ""
    date = ""
    with path.open(encoding="utf-8") as handle:
        for index, line in enumerate(handle):
            if index >= HEADER_LINES and heading:
                break
            if not heading and line.startswith("# "):
                heading = line[2:].strip()
            elif not date and index < HEADER_LINES:
                match = _HEADER_DATE_RE.match(line.strip())
                if match:
                    date = match.group("date")
    return heading, date


def collect(reports_dir: pathlib.Path) -> list[Report]:
    reports: dict[str, Report] = {}
    for path in sorted(reports_dir.iterdir()):
        match = _REPORT_RE.match(path.name)
        if not path.is_file() or not match:
            continue
        report = reports.setdefault(match.group("stem"), Report(match.group("stem")))
        report.files[match.group("lang")] = path.name

    for report in reports.values():
        stem_date = _STEM_DATE_RE.search(report.stem)
        if stem_date:
            report.date = "{y}-{m}-{d}".format(**stem_date.groupdict())
        for lang in LANGS:
            if lang not in report.files:
                continue
            heading, date = read_header(reports_dir / report.files[lang])
            if not report.title and heading:
                report.title = clean_title(heading)
            if not report.date and date:
                report.date = date
        if not report.title:
            report.title = report.stem

    return sorted(
        reports.values(),
        key=lambda r: (-(r.number if r.number is not None else -1), r.stem),
    )


def render(reports: list[Report]) -> str:
    lines = [PREAMBLE, "## Index", ""]
    lines.append(f"{len(reports)} reports.")
    lines.append("")
    lines.append("| # | Title | Date | English | Korean |")
    lines.append("|---|-------|------|---------|--------|")
    for report in reports:
        number = (
            f"[#{report.number}]({REPO_URL}/pull/{report.number})"
            if report.number is not None
            else "-"
        )
        links = [
            f"[{lang}]({report.files[lang]})" if lang in report.files else "-"
            for lang in LANGS
        ]
        lines.append(
            f"| {number} | {report.title} | {report.date or '-'} | {links[0]} | {links[1]} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None, reports_dir: pathlib.Path = REPORTS_DIR) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if the committed index differs from the generated one",
    )
    args = parser.parse_args(argv)

    index_path = reports_dir / INDEX_NAME
    expected = render(collect(reports_dir))
    if args.check:
        current = index_path.read_text(encoding="utf-8") if index_path.exists() else ""
        if current != expected:
            print(
                f"{index_path.relative_to(reports_dir.parent)} is stale; "
                "run `make reports-index` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"{index_path.name} is up to date.")
        return 0

    index_path.write_text(expected, encoding="utf-8")
    print(f"wrote {index_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

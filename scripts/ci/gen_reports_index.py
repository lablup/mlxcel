"""Generate, or check, the per-release indexes of ``TECHNICAL_REPORTS/``.

Rationale
---------
``TECHNICAL_REPORTS/`` holds one English and one Korean report per merged PR,
grouped into one folder per minor release line (``0.8/``, ``0.9/``; see
``TECHNICAL_REPORTS/README.md``). Before issue #1708 it had no index, so nobody
could map a PR number to its report. A hand-kept index drifts on the next
report, so the index is generated from the files and CI fails when a committed
copy differs from what this script would write.

Only released lines get a committed index
-----------------------------------------
Every merged PR commits its own report (``TECHNICAL_REPORTS/.keep-reports``),
so a committed index of the line under development would be one shared file
that every open PR rewrites at the same spot: concurrent PRs would conflict on
it, one after another. lablup/backend.ai-go dropped its tracked report table
for exactly that reason. A released line no longer receives reports, so its
index is written once, when the root ``Cargo.toml`` moves to the next line,
and then never changes. The current line has no committed index; ``--print``
shows it on demand.

What an index holds
-------------------
One row per report, keyed by its stem (the file name without ``.en.md`` or
``.ko.md``), newest number first:

- the number: the leading digits of the stem (``1058-...`` or ``pr-2475-...``),
  which is the PR the report covers in all but a handful of cases;
- the title: the report's first ``# `` heading, with the boilerplate
  ``Technical Report:`` and ``PR #N -`` prefixes removed (English file first);
- the date: the ``YYYYMMDD`` suffix of the stem, else a ``Date`` or ``Updated``
  line in the report's header, else blank;
- links to the English and Korean files. A missing language shows as ``-``.

Usage
-----
    scripts/ci/gen_reports_index.py                # write <X.Y>/README.md for released lines
    scripts/ci/gen_reports_index.py --check        # exit 1 if one is stale or the current line has one
    scripts/ci/gen_reports_index.py --print [X.Y]  # print a line's index (default: current line)

Run ``make reports-index`` in the PR that bumps the workspace version to a new
minor line, and after backfilling a report into a released line.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
REPORTS_DIR = ROOT / "TECHNICAL_REPORTS"
INDEX_NAME = "README.md"
CARGO_TOML = ROOT / "Cargo.toml"
_FOLDER_RE = re.compile(r"^(?P<major>\d+)\.(?P<minor>\d+)$")
_VERSION_RE = re.compile(r'^version\s*=\s*"(?P<major>\d+)\.(?P<minor>\d+)\.', re.M)
LANGS = ("en", "ko")
REPO_URL = "https://github.com/lablup/mlxcel"

_REPORT_RE = re.compile(r"^(?P<stem>.+)\.(?P<lang>en|ko)\.md$")
_NUMBER_RE = re.compile(r"^(?:pr-)?(?P<num>\d+)-")
_STEM_DATE_RE = re.compile(r"-(?P<y>20\d\d)(?P<m>[01]\d)(?P<d>[0-3]\d)$")
_HEADER_DATE_RE = re.compile(
    r"^\*\*(?:Date|Updated)(?::\*\*|\*\*:)\s*(?P<date>\d{4}-\d{2}-\d{2})"
)
_TITLE_PREFIX_RE = re.compile(r"^Technical [Rr]eport\s*:\s*")
_TITLE_REF_RE = re.compile(
    r"^(?:(?:PR|Issue)\s+#\d+|PR\s+\(issue\s+#\d+\))\s*(?:[-:,–—]\s*)?"
)
_TITLE_SUFFIX_RE = re.compile(
    r"\s*(?:\((?:PR |issue )?#\d+\)|[-:–—]\s*PR\s+#\d+)$"
)
HEADER_LINES = 20

PREAMBLE = """\
# Technical reports: {line}

One technical report per merged change in the {line} release line, each in
English (`.en.md`) and Korean (`.ko.md`). The number is the one in the file
name, which is the PR the report covers in nearly every case. See
[`../README.md`](../README.md) for the layout of `TECHNICAL_REPORTS/`.

This index is generated by `scripts/ci/gen_reports_index.py`. Do not edit it by
hand: run `make reports-index` after backfilling a report here. CI fails when
this file is stale.
"""


class Report:
    def __init__(self, stem: str) -> None:
        self.stem = stem
        self.files: dict[str, str] = {}
        self.title = ""
        self.date = ""

    @property
    def number(self) -> int | None:
        match = _NUMBER_RE.match(self.stem)
        return int(match.group("num")) if match else None


def clean_title(heading: str) -> str:
    title = heading.strip()
    title = _TITLE_PREFIX_RE.sub("", title)
    title = _TITLE_REF_RE.sub("", title)
    title = _TITLE_SUFFIX_RE.sub("", title)
    # Keep the table a table: a raw pipe would split the cell.
    title = title.replace("|", "\\|")
    return title.replace("—", "-").strip()


def read_header(path: pathlib.Path) -> tuple[str, str]:
    """Return (first H1 heading, header date) from the top of a report."""
    heading = ""
    date = ""
    with path.open(encoding="utf-8") as handle:
        for index, line in enumerate(handle):
            if index >= HEADER_LINES and heading:
                break
            if not heading and line.startswith("# "):
                heading = line[2:].strip()
            elif not date and index < HEADER_LINES:
                match = _HEADER_DATE_RE.match(line.strip())
                if match:
                    date = match.group("date")
    return heading, date


def collect(reports_dir: pathlib.Path) -> list[Report]:
    reports: dict[str, Report] = {}
    for path in sorted(reports_dir.iterdir()):
        match = _REPORT_RE.match(path.name)
        if not path.is_file() or not match:
            continue
        report = reports.setdefault(match.group("stem"), Report(match.group("stem")))
        report.files[match.group("lang")] = path.name

    for report in reports.values():
        stem_date = _STEM_DATE_RE.search(report.stem)
        if stem_date:
            report.date = "{y}-{m}-{d}".format(**stem_date.groupdict())
        for lang in LANGS:
            if lang not in report.files:
                continue
            heading, date = read_header(reports_dir / report.files[lang])
            if not report.title and heading:
                report.title = clean_title(heading)
            if not report.date and date:
                report.date = date
        if not report.title:
            report.title = report.stem

    return sorted(
        reports.values(),
        key=lambda r: (-(r.number if r.number is not None else -1), r.stem),
    )


def render(line: str, reports: list[Report]) -> str:
    lines = [PREAMBLE.format(line=line), "## Index", ""]
    lines.append(f"{len(reports)} reports.")
    lines.append("")
    lines.append("| # | Title | Date | English | Korean |")
    lines.append("|---|-------|------|---------|--------|")
    for report in reports:
        number = (
            f"[#{report.number}]({REPO_URL}/pull/{report.number})"
            if report.number is not None
            else "-"
        )
        links = [
            f"[{lang}]({report.files[lang]})" if lang in report.files else "-"
            for lang in LANGS
        ]
        lines.append(
            f"| {number} | {report.title} | {report.date or '-'} | {links[0]} | {links[1]} |"
        )
    return "\n".join(lines) + "\n"


def folder_line(name: str) -> tuple[int, int] | None:
    match = _FOLDER_RE.match(name)
    return (int(match.group("major")), int(match.group("minor"))) if match else None


def current_line(cargo_toml: pathlib.Path = CARGO_TOML) -> tuple[int, int]:
    match = _VERSION_RE.search(cargo_toml.read_text(encoding="utf-8"))
    if not match:
        raise SystemExit(f"no workspace version in {cargo_toml}")
    return int(match.group("major")), int(match.group("minor"))


def line_folders(reports_dir: pathlib.Path) -> list[tuple[tuple[int, int], pathlib.Path]]:
    folders = []
    for path in reports_dir.iterdir():
        line = folder_line(path.name)
        if path.is_dir() and line is not None:
            folders.append((line, path))
    return sorted(folders)


def main(
    argv: list[str] | None = None,
    reports_dir: pathlib.Path = REPORTS_DIR,
    current: tuple[int, int] | None = None,
) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if a released line's index is stale or the current line has one",
    )
    mode.add_argument(
        "--print",
        nargs="?",
        const="",
        metavar="X.Y",
        dest="print_line",
        help="print one line's index to stdout (default: the current line)",
    )
    args = parser.parse_args(argv)
    if current is None:
        current = current_line()
    current_name = f"{current[0]}.{current[1]}"

    if args.print_line is not None:
        name = args.print_line or current_name
        folder = reports_dir / name
        if folder_line(name) is None or not folder.is_dir():
            print(f"no release-line folder {name!r} under {reports_dir.name}/", file=sys.stderr)
            return 1
        sys.stdout.write(render(name, collect(folder)))
        return 0

    problems = []
    for line, folder in line_folders(reports_dir):
        index_path = folder / INDEX_NAME
        shown = index_path.relative_to(reports_dir.parent)
        if line >= current:
            if index_path.exists():
                problems.append(
                    f"{shown}: {folder.name} is the line under development, which has no committed "
                    "index (every report PR would conflict on it); delete it and use "
                    "`scripts/ci/gen_reports_index.py --print`"
                )
            continue
        expected = render(folder.name, collect(folder))
        if args.check:
            existing = index_path.read_text(encoding="utf-8") if index_path.exists() else ""
            if existing != expected:
                problems.append(f"{shown} is stale; run `make reports-index` and commit the result")
        elif not index_path.exists() or index_path.read_text(encoding="utf-8") != expected:
            index_path.write_text(expected, encoding="utf-8")
            print(f"wrote {shown}")

    for problem in problems:
        print(problem, file=sys.stderr)
    if problems:
        return 1
    if args.check:
        print(f"release-line indexes are up to date (current line {current_name} has none).")
    return 0


if __name__ == "__main__":
    sys.exit(main())

/* global process, console */
/**
 * Writes, or with --check verifies, public/astryx-layer-slide-rules.css.
 *
 * Astryx's popover Layer needs a set of @position-try rules. When no element with
 * id="astryx-layer-slide-rules" exists, it inserts them as a <style> element, which the
 * served CSP (style-src 'self') blocks. index.html links this file under that id instead,
 * so Astryx finds the element and inserts nothing. The rules are generated from the
 * installed Astryx core, so an upgrade that changes them fails --check until regenerated.
 *
 * Usage: node scripts/layer-slide-rules.mjs [--check]
 */
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const webui = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SLIDE_RULES_PATH = join(webui, 'public', 'astryx-layer-slide-rules.css');
const HEADER = '/* Generated by scripts/layer-slide-rules.mjs from @astryxdesign/core (via @lablup/ui-common). Do not edit. */\n';

/** The rules the installed Astryx core would insert, as the shipped file's text. */
export async function expectedSlideRules() {
  // Astryx core is ui-common's own dependency: resolve it next to the installed ui-common.
  const uiCommon = realpathSync(join(webui, 'node_modules', '@lablup', 'ui-common'));
  const core = join(uiCommon, '..', '..', '@astryxdesign', 'core');
  const module = await import(pathToFileURL(join(core, 'dist', 'Layer', 'layerSlideRules.js')).href);
  return `${HEADER}${module.slideRulesCss()}\n`;
}

async function main() {
  const expected = await expectedSlideRules();
  if (process.argv.includes('--check')) {
    let actual = '';
    try { actual = readFileSync(SLIDE_RULES_PATH, 'utf8'); } catch { /* reported below */ }
    if (actual !== expected) {
      console.error('public/astryx-layer-slide-rules.css is stale; run node scripts/layer-slide-rules.mjs');
      process.exit(1);
    }
    return;
  }
  writeFileSync(SLIDE_RULES_PATH, expected);
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) await main();

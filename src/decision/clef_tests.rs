const TYPES: &[QuestionKind] = &[
    QuestionKind::Choice,
    QuestionKind::Score,
    QuestionKind::Bool,
];

pub(super) fn fixture() -> Value {
    serde_json::from_str(include_str!(
        "../../tests/fixtures/decision/clef_parity.json"
    ))
    .expect("fixture parses")
}

/// `models/clef-flash-mlx-8bit` when it holds a complete checkpoint; `None`
/// skips.
pub(super) fn checkpoint(need_weights: bool) -> Option<PathBuf> {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("models/clef-flash-mlx-8bit");
    let ready = dir.join("tokenizer.json").is_file()
        && dir.join("config.json").is_file()
        && (!need_weights || dir.join("model.safetensors.index.json").is_file());
    if !ready {
        eprintln!(
            "skipping: models/clef-flash-mlx-8bit not present \
             (mlxcel download nativ-community/clef-flash-MLX-8bit)"
        );
    }
    ready.then_some(dir)
}

pub(super) fn cats() -> image::DynamicImage {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/sam3/cats.png");
    image::DynamicImage::ImageRgb8(image::open(path).expect("cats decodes").to_rgb8())
}

pub(super) fn validated(questions: &Value, media: MediaPresence) -> Vec<(String, Question)> {
    validate_questions(
        TYPES,
        &[MediaKind::Image, MediaKind::Video],
        Some(&json!("state")),
        questions,
        media,
    )
    .expect("valid questions")
}

fn question(spec: Value) -> Question {
    validated(&json!({ "q": spec }), MediaPresence::default())
        .remove(0)
        .1
}

#[test]
fn published_clef_flash_config_is_detected() {
    let config: Value = serde_json::from_str(include_str!(
        "../../tests/fixtures/decision/clef_flash_config.json"
    ))
    .expect("config parses");
    assert_eq!(
        detect_decision_kind(&config).expect("clef"),
        DecisionKind::Clef
    );
    assert_eq!(DecisionKind::Clef.as_str(), "clef");
    let head = HeadConfig::from_config(&config).expect("head_config");
    assert_eq!(
        (
            head.hidden_size,
            head.width,
            head.routing_layers,
            head.layers,
            head.heads,
            head.feedforward
        ),
        (4096, 1024, 2, 4, 16, 4096)
    );

    let mut stock = config.clone();
    stock["model_type"] = json!("qwen3_5");
    stock.as_object_mut().expect("object").remove("head_config");
    let error = detect_decision_kind(&stock).expect_err("stock Qwen3.5 VLM");
    assert!(error.to_string().contains("qwen3_5"), "{error}");
}


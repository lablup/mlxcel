#[test]
fn answers_keep_request_order() {
    // Schema order is sorted (account, billing, technical); the answer
    // reports the request order and its argmax.
    let choice = question(json!({"type": "choice",
        "criteria": {"technical": null, "billing": null, "account": null}}));
    let labels = ["account", "billing", "technical"].map(String::from);
    let answer = clef_answer(&choice, &labels, &[0.1, 0.3, 0.6]).unwrap();
    let Answer::Choice {
        value,
        probabilities,
        metadata,
    } = answer
    else {
        panic!("choice answer");
    };
    assert_eq!(value, "technical");
    let order: Vec<&str> = probabilities
        .iter()
        .map(|(label, _)| label.as_str())
        .collect();
    assert_eq!(order, ["technical", "billing", "account"]);
    assert_eq!(metadata["confidence"], json!(0.6));

    let boolean = question(json!({"type": "bool"}));
    let answer = clef_answer(
        &boolean,
        &["true".into(), "false".into()],
        &[0.123_456, 0.876_544],
    )
    .unwrap();
    assert_eq!(
        answer.to_json(),
        json!({"type": "bool", "value": false, "probability": 0.1235})
    );

    let score = question(json!({"type": "score", "criteria": ["a", "b", "c"]}));
    let labels = ["0", "1", "2"].map(String::from);
    let answer = clef_answer(&score, &labels, &[0.2, 0.3, 0.5])
        .unwrap()
        .to_json();
    assert_eq!(answer["value"], json!(1.3));
    assert_eq!(
        answer["probabilities"],
        json!({"0": 0.2, "1": 0.3, "2": 0.5})
    );
    assert_eq!(answer["metadata"]["confidence"], json!(0.5));
    assert_eq!(
        answer["metadata"]["legend"],
        json!({"0": "a", "1": "b", "2": "c"})
    );
}

#[test]
fn head_sanitize_splits_pytorch_in_proj_and_renames_sequential_indices() {
    let mut raw = mlxcel_core::weights::WeightMap::new();
    let packed: Vec<f32> = (0..12).map(|v| v as f32).collect();
    raw.insert(
        "layers.0.self_attn.in_proj_weight".to_string(),
        mlxcel_core::from_slice_f32(&packed, &[6, 2]),
    );
    raw.insert(
        "head.residual_scorer.3.bias".to_string(),
        mlxcel_core::from_slice_f32(&[1.0], &[1]),
    );
    raw.insert(
        "evidence_layers.1.feedforward.3.weight".to_string(),
        mlxcel_core::from_slice_f32(&[1.0], &[1, 1]),
    );
    let out = sanitize_head_weights(raw).expect("sanitizes");
    let mut keys: Vec<&String> = out.keys().collect();
    keys.sort();
    assert_eq!(
        keys,
        [
            "head.evidence_layers.1.feedforward.1.weight",
            "head.layers.0.self_attn.key_proj.weight",
            "head.layers.0.self_attn.query_proj.weight",
            "head.layers.0.self_attn.value_proj.weight",
            "head.residual_scorer.1.bias",
        ]
    );
    let key = mlxcel_core::utils::array_to_vec_f32(&out["head.layers.0.self_attn.key_proj.weight"]);
    assert_eq!(key, [4.0, 5.0, 6.0, 7.0]);
}

/// Merged token count of one `[t, h, w]` fixture grid row, per temporal
/// group, and its group count.
fn merged(grid: &Value) -> (usize, usize) {
    let g: Vec<usize> = grid
        .as_array()
        .expect("grid")
        .iter()
        .map(|v| v.as_u64().expect("int") as usize)
        .collect();
    (g[0], g[1] / 2 * (g[2] / 2))
}

/// The media block of one fixture case, from upstream's grids.
fn fixture_media(tokenizer: &ClefTokenizer, case: &Value) -> Vec<u32> {
    let images: Vec<usize> = case["image_grid_thw"]
        .as_array()
        .map(|grids| {
            grids
                .iter()
                .map(|grid| {
                    let (t, n) = merged(grid);
                    t * n
                })
                .collect()
        })
        .unwrap_or_default();
    let videos: Vec<(usize, Vec<f64>)> = case["video_grid_thw"]
        .as_array()
        .map(|grids| {
            grids
                .iter()
                .map(|grid| {
                    let (t, n) = merged(grid);
                    // The fixture clip has 48 frames, sampled as upstream does.
                    let indices = linspace_indices(48, frame_count(48, &VideoSettings::DEFAULT));
                    let seconds = crate::qwen_vl::qwen_video_group_timestamps(&indices, 24.0, 2, t)
                        .expect("timestamps");
                    (n, seconds)
                })
                .collect()
        })
        .unwrap_or_default();
    if images.is_empty() && videos.is_empty() {
        return Vec::new();
    }
    media_block(tokenizer, &images, &videos).expect("media block")
}

#[test]
fn sequences_match_upstream_ids_and_spans() {
    let Some(dir) = checkpoint(false) else {
        return;
    };
    let tokenizer = ClefTokenizer::load(&dir).expect("tokenizer");
    for case in fixture()["sequences"].as_array().expect("sequences") {
        let name = case["name"].as_str().expect("name");
        let presence = MediaPresence {
            images: case["image_grid_thw"].is_array(),
            videos: case["video_grid_thw"].is_array(),
            audio: false,
        };
        let questions = validated(&case["questions"], presence);
        let state = Some(&case["state"]).filter(|state| !state.is_null());
        let media = fixture_media(&tokenizer, case);
        let built = sequence(&tokenizer, state, &questions, &media).expect("sequence");
        let expected: Vec<u32> = serde_json::from_value(case["ids"].clone()).expect("ids");
        assert_eq!(built.ids, expected, "{name}: ids");
        let rows = case["rows"].as_array().expect("rows");
        assert_eq!(built.rows.len(), rows.len(), "{name}: rows");
        for (row, want) in built.rows.iter().zip(rows) {
            let span: (usize, usize) =
                serde_json::from_value(want["question_span"].clone()).expect("span");
            let spans: Vec<(usize, usize)> =
                serde_json::from_value(want["option_spans"].clone()).expect("spans");
            let labels: Vec<String> =
                serde_json::from_value(want["labels"].clone()).expect("labels");
            assert_eq!(row.question_span, span, "{name}: question span");
            assert_eq!(row.option_spans, spans, "{name}: option spans");
            assert_eq!(row.labels, labels, "{name}: labels");
        }
    }
}

#[test]
fn media_grids_match_upstream_processor() {
    // The checkpoint's image bounds; cats.png (640 x 480) is on the 32-pixel
    // grid, so it keeps its size: 30 x 40 patches.
    let processor = Qwen2VLProcessor::new_with_norm(16, 2, 2, [0.5; 3], [0.5; 3])
        .with_pixel_bounds(65_536, 16_777_216);
    assert_eq!(processor.compute_grid_thw(&[cats()]), [(1, 30, 40)]);
    let sequences = &fixture()["sequences"];
    assert_eq!(sequences[1]["image_grid_thw"], json!([[1, 30, 40]]));
    // The fixture clip's 4 frames of 320 x 256 stay that size: 16 x 20.
    assert_eq!(sequences[3]["video_grid_thw"], json!([[2, 16, 20]]));
    assert_eq!(
        video_frame_size(4, 256, 320, 2, 32, &VideoSettings::DEFAULT).unwrap(),
        (256, 320)
    );
}

#[test]
fn a_schema_too_long_is_refused_and_a_long_state_is_truncated() {
    let Some(dir) = checkpoint(false) else {
        return;
    };
    let tokenizer = ClefTokenizer::load(&dir).expect("tokenizer");
    let long = "word ".repeat(MAX_LENGTH + 10);
    let questions = validated(
        &json!({"q": {"type": "bool", "instructions": long}}),
        MediaPresence::default(),
    );
    let error = sequence(&tokenizer, Some(&json!("hi")), &questions, &[]).expect_err("too long");
    let DecisionError::InvalidInput(message) = error else {
        panic!("not InvalidInput: {error:?}");
    };
    assert!(message.starts_with("schema requires "), "{message}");
    assert!(
        message.ends_with("tokens before state; maximum is 16384"),
        "{message}"
    );

    let questions = validated(&json!({"q": {"type": "bool"}}), MediaPresence::default());
    let state = json!(long);
    let built = sequence(&tokenizer, Some(&state), &questions, &[]).expect("truncated");
    assert_eq!(built.ids.len(), MAX_LENGTH);
    let short = sequence(&tokenizer, Some(&json!("hi")), &questions, &[]).expect("short");
    // The schema and suffix stay intact at the end.
    let tail = short.ids.len() - short.rows[0].question_span.0;
    assert_eq!(
        built.ids[MAX_LENGTH - tail..],
        short.ids[short.ids.len() - tail..]
    );
}

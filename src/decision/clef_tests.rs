#[test]
fn options_follow_upstream_order_and_defaults() {
    let choice = question(json!({"type": "choice",
        "criteria": {"technical": "Bugs", "billing": null, "account": "Login"}}));
    let ids: Vec<String> = options(&choice).into_iter().map(|(id, _)| id).collect();
    assert_eq!(ids, ["account", "billing", "technical"]);
    assert_eq!(options(&choice)[1].1, Value::Null);

    let listed = question(json!({"criteria": ["sales", "billing"]}));
    assert_eq!(
        options(&listed),
        [
            ("billing".to_string(), Value::Null),
            ("sales".to_string(), Value::Null)
        ]
    );

    let plain = question(json!({"type": "bool"}));
    assert_eq!(
        options(&plain),
        [
            (
                "true".to_string(),
                json!("The proposition is true or the answer is yes.")
            ),
            (
                "false".to_string(),
                json!("The proposition is false or the answer is no.")
            ),
        ]
    );
    let described = question(json!({"type": "noul", "criteria": {"true": null, "false": "No"}}));
    assert_eq!(
        options(&described),
        [
            ("true".to_string(), Value::Null),
            ("false".to_string(), json!("No"))
        ]
    );

    let score = question(json!({"type": "score", "criteria": ["low", {"n": 2}]}));
    assert_eq!(
        options(&score),
        [
            ("0".to_string(), json!("low")),
            ("1".to_string(), json!({"n": 2}))
        ]
    );
}

#[test]
fn video_sampling_matches_numpy() {
    let settings = VideoSettings::DEFAULT;
    // int(48 / 24 * 2) = 4 frames; linspace(0, 47, 4) = 0, 15.67, 31.33, 47.
    assert_eq!(frame_count(48, &settings), 4);
    assert_eq!(linspace_indices(48, 4), [0, 16, 31, 47]);
    // A short clip takes min_frames, a shorter one every frame.
    assert_eq!(frame_count(10, &settings), 4);
    assert_eq!(frame_count(3, &settings), 3);
    // A long clip is capped at max_frames.
    assert_eq!(frame_count(24 * 1000, &settings), 768);
    // NumPy rounds half to even: linspace(0, 9, 3) = 0, 4.5, 9.
    assert_eq!(linspace_indices(10, 3), [0, 4, 9]);
    assert_eq!(linspace_indices(5, 1), [0]);
}

#[test]
fn video_frames_share_the_clip_pixel_budget() {
    let settings = VideoSettings::DEFAULT;
    // Inside the budget: snapped to the 32-pixel grid, unchanged here.
    assert_eq!(
        video_frame_size(4, 256, 320, 2, 32, &settings).unwrap(),
        (256, 320)
    );
    // 8 frames of 1080p: beta = sqrt(8 * 1080 * 1920 / 786432).
    assert_eq!(
        video_frame_size(8, 1080, 1920, 2, 32, &settings).unwrap(),
        (224, 416)
    );
    // Below the floor: grown.
    assert_eq!(
        video_frame_size(2, 64, 64, 2, 32, &settings).unwrap(),
        (256, 256)
    );
    assert!(matches!(
        video_frame_size(1, 64, 64, 2, 32, &settings),
        Err(DecisionError::InvalidInput(_))
    ));
}


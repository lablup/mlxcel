#[test]
fn a_qwen3_vl_config_reads_its_nested_text_config() {
    let mut nested = config();
    nested["model_type"] = json!("qwen3_vl_text");
    let outer = json!({
        "model_type": "qwen3_vl",
        "architectures": ["Qwen3VLForConditionalGeneration"],
        "text_config": nested,
    });
    let refs = refs();
    let enc =
        Qwen3TextEncoder::from_weights(&outer, weights_with("model.language_model.")).unwrap();
    let got = enc
        .hidden_states(&refs["input_ids"], Some(&refs["attention_mask"]))
        .unwrap();
    let want = encoder()
        .hidden_states(&refs["input_ids"], Some(&refs["attention_mask"]))
        .unwrap();
    assert!(rel_rms(&got[LAYERS], &want[LAYERS]) < 1e-6);
}

#[test]

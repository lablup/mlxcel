/// Directory of a real Qwen3 checkpoint: `MLXCEL_TEST_QWEN3_DIR`, else the
/// mlxcel store copy of `mlx-community/Qwen3-0.6B-4bit`.
fn real_checkpoint() -> Option<PathBuf> {
    let dir = std::env::var_os("MLXCEL_TEST_QWEN3_DIR")
        .map(PathBuf::from)
        .or_else(|| {
            std::env::var_os("HOME").map(|h| {
                PathBuf::from(h).join(".cache/mlxcel/models/mlx-community/Qwen3-0.6B-4bit")
            })
        })?;
    dir.join("config.json").exists().then_some(dir)
}

/// On a real (quantized) checkpoint the last hidden state, once normed and
/// projected, must reproduce the logits of the ordinary generation path, so the
/// all-layers path computes the same network.
#[test]
#[ignore = "needs a Qwen3 checkpoint (mlx-community/Qwen3-0.6B-4bit or MLXCEL_TEST_QWEN3_DIR)"]
fn real_qwen3_hidden_states_reproduce_the_generation_logits() {
    let Some(dir) = real_checkpoint() else {
        eprintln!("skipping: no Qwen3 checkpoint found");
        return;
    };
    let enc = Qwen3TextEncoder::load(&dir).unwrap();
    let batch = ids(&[&[9707, 11, 1879, 0, 358, 1079, 264, 1273, 13]]);
    let states = enc.hidden_states(&batch, None).unwrap();
    assert_eq!(states.len(), enc.num_layers() + 1);
    let last = enc.model.norm.forward(&states[enc.num_layers()]);
    let from_encoder = enc.model.embed_tokens.as_linear(&last);

    let (model, _) = crate::models::qwen3::Qwen3Model::load(&dir).unwrap();
    let mut caches = model.make_caches();
    let reference = model.forward(&batch, &mut caches, None);
    let err = rel_rms(&from_encoder, &reference);
    eprintln!("encoder vs generation logits rel-RMS = {err:e}");
    assert!(err < 1e-3, "logits rel-RMS {err}");
    let argmax = |a: &MlxArray| {
        let v = to_vec(a);
        let w = *mlxcel_core::array_shape(a).last().unwrap() as usize;
        v.chunks(w)
            .map(|row| {
                row.iter()
                    .enumerate()
                    .max_by(|a, b| a.1.total_cmp(b.1))
                    .unwrap()
                    .0
            })
            .collect::<Vec<_>>()
    };
    assert_eq!(
        argmax(&from_encoder),
        argmax(&reference),
        "greedy tokens must agree"
    );
}

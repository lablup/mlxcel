#[test]
fn every_checkpoint_key_layout_loads_the_same_model() {
    let refs = refs();
    let reference = encoder()
        .hidden_states(&refs["input_ids"], Some(&refs["attention_mask"]))
        .unwrap();
    for prefix in [
        "",
        "model.language_model.",
        "language_model.model.",
        "language_model.",
    ] {
        let mut weights = weights_with(prefix);
        // Tensors a conditioner checkpoint carries and this path must drop.
        weights.insert(
            format!("{prefix}lm_head.weight"),
            det("lm_head", &[VOCAB, HIDDEN], 0.1, 0.0),
        );
        weights.insert(
            "visual.patch_embed.weight".into(),
            det("visual", &[4, 4], 0.1, 0.0),
        );
        weights.insert(
            "model.visual.blocks.0.attn.qkv.weight".into(),
            det("visual2", &[4, 4], 0.1, 0.0),
        );
        let enc = Qwen3TextEncoder::from_weights(&config(), weights)
            .unwrap_or_else(|e| panic!("prefix {prefix:?}: {e:#}"));
        let got = enc
            .hidden_states(&refs["input_ids"], Some(&refs["attention_mask"]))
            .unwrap();
        for (a, b) in got.iter().zip(&reference) {
            assert!(rel_rms(a, b) < 1e-6, "prefix {prefix:?}");
        }
    }
}


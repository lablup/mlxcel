#[test]
fn load_reads_a_directory_and_applies_the_dtype_policy() {
    let dir = tempfile::TempDir::new().unwrap();
    std::fs::write(dir.path().join("config.json"), config().to_string()).unwrap();
    // Store the tiny model as bf16 safetensors, as a real conditioner ships.
    crate::imagegen::testing::write_bf16_safetensors(
        &dir.path().join("model.safetensors"),
        &weights_with("model."),
    );

    let enc = Qwen3TextEncoder::load(dir.path()).unwrap();
    let batch = ids(&[&[3, 10, 7, 22]]);
    let states = enc.hidden_states(&batch, None).unwrap();
    assert!(to_vec(&states[LAYERS]).iter().all(|v| v.is_finite()));
    // Close to the f32 model: bf16 storage costs about 1e-2.
    let want = encoder().hidden_states(&batch, None).unwrap();
    assert!(rel_rms(&states[LAYERS], &want[LAYERS]) < 5e-2);
}

